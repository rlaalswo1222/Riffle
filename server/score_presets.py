"""검증된 악보 파일의 마디 시스템 좌표.

파일 이름은 바뀔 수 있으므로 PDF 바이트의 SHA-256으로 식별한다. 좌표는
PDF 페이지 비율이며, end_measure는 해당 시스템 범위의 끝(미포함)이다.
"""
import hashlib


_LEFT = 0.091
_RIGHT = 0.960


def _systems(rows: list[tuple[int, float, int]]) -> list[dict]:
    return [
        {
            "page": page,
            "y": y,
            "measure": measure,
            "x_start": _LEFT,
            "x_end": _RIGHT,
            "end_measure": measure + 4,
        }
        for page, y, measure in rows
    ]


